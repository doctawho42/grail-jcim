"""The sentence the MetaTox comparison may be stated in, derived rather than written.

Section 0.2b fixes that the comparison is the sweep and not a cell. Written by hand, that
sentence was wrong within an hour: it said the point estimate leads at k=15 and k=20, which holds
for the whole bank and not for the trained budget, where the gap is -0.0346 and -0.0647 and the
second of those separates against us.

So the sentence is generated from `results/deployment_table.json` and a test holds the
preregistration to containing exactly what this produces. A claim that cannot drift from its
artifact is worth more than one that is merely correct today.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "results/deployment_table.json"
ARMS = {"whole bank": "whole bank", "trained budget": "trained budget"}
COMPARATORS = ("metatox", "sygma", "metapredictor")


def _fmt(ks):
    ks = [str(k) for k in ks]
    if not ks:
        return "no budget"
    if len(ks) == 1:
        return f"k = {ks[0]}"
    return "k = " + ", ".join(ks[:-1]) + " and " + ks[-1]


def claim(table_path: Path = TABLE) -> str:
    d = json.loads(Path(table_path).read_text())
    budgets = [int(k) for k in d["recall_micro"]]
    lines = []
    for arm in ARMS:
        leads, sep, trails_sep = [], [], []
        for k in budgets:
            c = d["contrasts"][str(k)][f"{arm} - metatox"]
            if c["gap"] > 0:
                leads.append(k)
                if c["excludes_zero"]:
                    sep.append(k)
            elif c["excludes_zero"]:
                trails_sep.append(k)
        ties = [k for k in budgets if k not in sep and k not in trails_sep]
        line = (f"The {arm} leads MetaTox at {_fmt(leads)}, with the paired-bootstrap interval "
                f"excluding zero at {_fmt(sep)}.")
        if trails_sep:
            line += f" It trails with the interval excluding zero at {_fmt(trails_sep)}."
        if ties:
            line += f" At {_fmt(ties)} the interval does not separate."
        lines.append(line)
    # every comparator the artifact carries, not the one the author happened to read
    for comp in COMPARATORS:
        if comp == "metatox" or f"whole bank - {comp}" not in d["contrasts"][str(budgets[0])]:
            continue
        for arm in ARMS:
            leads, sep, trails = [], [], []
            for k in budgets:
                c = d["contrasts"][str(k)][f"{arm} - {comp}"]
                if c.get("gap", 0) > 0:
                    leads.append(k)
                    if c.get("excludes_zero"):
                        sep.append(k)
                elif c.get("excludes_zero"):
                    trails.append(k)
            line = f"Against {comp}, the {arm} leads at {_fmt(leads)}"
            line += f", separating at {_fmt(sep)}." if sep else " and separates nowhere."
            if trails:
                line += f" It trails with the interval excluding zero at {_fmt(trails)}."
            lines.append(line)

    n = d["population"]["n"]
    mean = d["mean_output_length"]
    lines.append("Mean list length: " +
                 ", ".join(f"{a} {mean[a]}" for a in mean) + f", on {n} substrates.")
    return "\n".join("> " + x for x in lines)


CLAIM_TEX = ROOT / "paper2" / "claim.tex"
PREREG = ROOT / "paper2" / "preregistration.md"
# The two sentences the generated block sits between in the preregistration. Anchors rather than
# line numbers, and both are required: a missing anchor means the surrounding prose was rewritten
# and the block's place has to be decided by a person, not guessed by this script.
OPENS = "So the claim is stated as it falls:"
CLOSES = "That block is generated from"


def write(block: str | None = None) -> list:
    r"""Put the generated block in both places that quote it, and say which changed.

    The block was regenerated by hand for a while. That is the step the gate kept catching:
    the comparison artifact was corrected in one commit and the sentence derived from it was
    not re-derived until a test said so, three weeks later. A printing script and a human
    paste is not a reproduction path, so the script writes its own outputs.
    """
    block = claim() if block is None else block
    bare = "\n".join(line[2:] if line.startswith("> ") else line
                     for line in block.splitlines()) + "\n"
    changed = []

    def name(path):
        """Repository-relative where it can be, absolute otherwise -- a test runs this on a
        temporary pair and a relative_to that raises is not a reporting detail there."""
        try:
            return str(Path(path).relative_to(ROOT))
        except ValueError:
            return str(path)

    if CLAIM_TEX.read_text() != bare:
        CLAIM_TEX.write_text(bare)
        changed.append(name(CLAIM_TEX))

    src = PREREG.read_text()
    i, j = src.find(OPENS), src.find(CLOSES)
    if i < 0 or j < 0 or j < i:
        raise SystemExit(
            f"the preregistration's anchors for the generated block were not found "
            f"({OPENS!r} at {i}, {CLOSES!r} at {j}); the prose around the block has changed "
            f"and where the block belongs is a decision, not something to guess")
    head = src[:i + len(OPENS)]
    tail = src[j:]
    out = head + "\n\n" + block + "\n\n" + tail
    if out != src:
        PREREG.write_text(out)
        changed.append(name(PREREG))
    return changed


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true",
                    help="put the block in paper2/claim.tex and the preregistration")
    a = ap.parse_args()
    if not a.write:
        print(claim())
    else:
        touched = write()
        print("\n".join(f"wrote {f}" for f in touched) if touched
              else "both copies already match the artifact")
